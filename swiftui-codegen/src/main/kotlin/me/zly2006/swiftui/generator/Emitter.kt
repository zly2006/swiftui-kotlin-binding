fun generate(destination: File) {
    check(bindings.map { it.abi }.distinct().size == bindings.size)
    bindings.forEach { binding ->
        check(binding.fields.map { it.name }.distinct().size == binding.fields.size)
        check(binding.modifier == null || binding.children == Children.One)
    }
    fun output(name: String, body: String) { File(destination, name).apply { parentFile.mkdirs(); writeText(GENERATED_NOTICE + body) } }
    output("include/NativeUI.h", header())
    output("swift/GeneratedNativeUI.swift", swiftBindings())
    output("common/NativeApi.kt", kotlinApi())
    output("common/NativeComponents.kt", composeComponents())
    output("macos/GeneratedMacosBackend.kt", macosBindings())
    output("api-manifest.tsv", "binding\tC ABI\tchildren\tcallback\tstatus\n" + bindings.joinToString("\n", postfix = "\n") { "${it.name}\tsui_node_${it.abi}_create/update\t${it.children}\t${it.callback?.name ?: "none"}\tgenerated; native compilation and behavior require separate evidence" })
    output("component-whitelist.tsv", "family\tselected adapter\tofficial documentation\n" + componentWhitelist.flatMap { entry -> entry.adapters.sorted().map { "${entry.family}\t$it\t${entry.documentation}" } }.joinToString("\n", postfix = "\n"))
    output("deferred-capabilities.tsv", "family\tcapability\tstatus\n" + componentWhitelist.flatMap { entry -> entry.next.map { "${entry.family}\t$it\tplanned; semantic mapping and behavior verification pending" } }.joinToString("\n", postfix = "\n"))
    println("Generated ${bindings.size} native mappings into ${destination.absolutePath}")
}
