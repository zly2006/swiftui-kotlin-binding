private fun header() =
    buildString {
        append("#pragma once\n#include <stdint.h>\ntypedef void* SUI_Node;\n")
        append(
            "void* sui_path_create(void);\nint32_t sui_path_live(void);\nint64_t sui_path_constructions(void);\nvoid sui_path_move(void* path, double x, double y);\nvoid sui_path_line(void* path, double x, double y);\nvoid sui_path_curve(void* path, double x, double y, double c1x, double c1y, double c2x, double c2y);\nvoid sui_path_arc(void* path, double x, double y, double radius, double start, double end, int32_t clockwise);\nvoid sui_path_close(void* path);\nvoid sui_path_release(void* path);\n",
        )
        bindings.mapNotNull { it.callback }.distinctBy { it.cType() }.forEach { callback ->
            append(
                "typedef void (*${callback.cType()})(void* context${callback.payloadAbi().joinToString("") { ", ${it.c} ${it.name}" }});\n",
            )
        }
        for (b in bindings) {
            val fields = b.fields.flatMap { it.abi() }.map { "${it.c} ${it.name}" }
            val callback = b.callback?.let { listOf("${it.cType()} callback", "void* context") }.orEmpty()
            append("SUI_Node sui_node_${b.abi}_create(${(fields + callback).joinToString().ifEmpty { "void" }});\n")
            append("void sui_node_${b.abi}_update(${(listOf("SUI_Node node") + fields).joinToString()});\n")
        }
        append(
            """
            void sui_node_insert(SUI_Node parent, SUI_Node child, int32_t index);
            void sui_node_remove(SUI_Node parent, int32_t index, int32_t count);
            void sui_node_move(SUI_Node parent, int32_t from, int32_t to, int32_t count);
            void sui_node_clear(SUI_Node parent);
            void sui_node_release(SUI_Node node);
            void* sui_tree_host_create(SUI_Node root);
            void sui_tree_host_release(void* host);
            int32_t sui_tree_live_nodes(void);
            int32_t sui_tree_live_hosts(void);
            int64_t sui_tree_property_updates(void);
            int64_t sui_tree_body_evaluations(void);
            void sui_node_debug_action(SUI_Node node);
            void sui_node_debug_boolean(SUI_Node node, int32_t value);
            void sui_node_debug_string(SUI_Node node, const char* value);
            void sui_node_debug_double(SUI_Node node, double value);
            void sui_node_debug_color(SUI_Node node, int32_t valueKind, double valueRed, double valueGreen, double valueBlue, double valueAlpha, double valueOpacity);
            void sui_node_debug_size(SUI_Node node, double valueWidth, double valueHeight);
            """.trimIndent() + "\n",
        )
    }

private fun ApiRef.documentation(): String {
    val framework = if (module == "SwiftUICore") "swiftui" else module.lowercase()
    val type = owner.lowercase().replace('.', '/')
    return "https://developer.apple.com/documentation/$framework/$type"
}

private fun Binding.documentation() =
    references.distinct().joinToString("\n") {
        " *\n * [${it.owner}${it.member?.let { member -> ".$member" }.orEmpty()}](${it.documentation()}) in Apple Documentation\n"
    }

private fun Binding.kdoc(
    summary: String,
    property: Boolean = false,
    component: Boolean = false,
    backend: Boolean = false,
    update: Boolean = false,
): String =
    buildString {
        append("/**\n * $summary\n")
        append(documentation())
        if (!backend) fields.forEach { append(" * @${if (property) "property" else "param"} ${it.name} Native `${it.name}` parameter.\n") }
        if (backend) {
            if (update) append(" * @param element Existing element created by this backend's $name factory.\n")
            append(" * @param config Immutable native configuration.\n")
            if (!update) callback?.let { append(" * @param ${it.name} Receives native events; update Kotlin state here.\n") }
        }
        if (component) {
            callback?.let { append(" * @param ${it.name} Callback invoked by the native control; keep controlled state in Kotlin.\n") }
            append(" * @param modifier Native-backed Compose modifier chain, ordered from outermost to innermost.\n")
            if (slots.isNotEmpty()) {
                slots.forEach { append(" * @param $it Composable content for the native $it slot.\n") }
            } else if (children != Children.None) {
                append(" * @param content Child content rendered by the native container.\n")
            }
        }
        append(" */\n")
    }

